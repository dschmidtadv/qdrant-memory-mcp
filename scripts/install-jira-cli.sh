#!/usr/bin/env bash
################################################################################
# install-jira-cli.sh
#
# Installs a `jira` shim to ~/.local/bin so the JIRA Manager skill can be
# invoked from ANY repository as simply:
#
#   jira check
#   jira --project ADO comment ADO-241 --body "h2. Update..."
#
# The shim is a thin wrapper that delegates to the canonical jira_client.py
# in this repo. No path hardcoding is needed in any other project.
#
# Usage:
#   bash scripts/install-jira-cli.sh
#   or via Make:
#   make install-jira
#
# Uninstall:
#   rm ~/.local/bin/jira
#
################################################################################

set -euo pipefail

# Color codes
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
JIRA_CLIENT="${PROJECT_ROOT}/agent/skills/jira-manager/scripts/jira_client.py"
INSTALL_DIR="${HOME}/.local/bin"
SHIM_PATH="${INSTALL_DIR}/jira"

echo -e "${BLUE}ℹ${NC} JIRA CLI Installer"
echo -e "${BLUE}ℹ${NC} Source: ${JIRA_CLIENT}"
echo -e "${BLUE}ℹ${NC} Target: ${SHIM_PATH}"
echo ""

# Verify source exists
if [[ ! -f "${JIRA_CLIENT}" ]]; then
    echo -e "${RED}✗${NC} jira_client.py not found at: ${JIRA_CLIENT}"
    echo "  Run this script from the qdrant-memory-mcp project root."
    exit 1
fi

# Create ~/.local/bin if it doesn't exist
if [[ ! -d "${INSTALL_DIR}" ]]; then
    mkdir -p "${INSTALL_DIR}"
    echo -e "${GREEN}✓${NC} Created ${INSTALL_DIR}"
fi

# Write the shim
cat > "${SHIM_PATH}" << EOF
#!/usr/bin/env bash
# jira — JIRA Manager CLI shim
# Auto-generated by install-jira-cli.sh
# Source: ${JIRA_CLIENT}
#
# Delegates to the canonical jira_client.py in qdrant-memory-mcp.
# sys.path injection in jira_client.py ensures jira_config is importable
# regardless of the caller's cwd.
#
# Usage:
#   jira check
#   jira --project ADO check
#   jira --project ADO comment ADO-241 --body "h2. Update..."
#   jira --env-file /path/to/.env check
exec python3 "${JIRA_CLIENT}" "\$@"
EOF

chmod +x "${SHIM_PATH}"
echo -e "${GREEN}✓${NC} Installed: ${SHIM_PATH}"

# Check if ~/.local/bin is on PATH
if echo "${PATH}" | grep -q "${INSTALL_DIR}"; then
    echo -e "${GREEN}✓${NC} ${INSTALL_DIR} is already on PATH"
else
    echo ""
    echo -e "${YELLOW}⚠${NC}  ${INSTALL_DIR} is NOT on your PATH."
    echo "   Add this to your ~/.zshrc or ~/.bashrc:"
    echo ""
    echo '   export PATH="$HOME/.local/bin:$PATH"'
    echo ""
    echo "   Then reload your shell:"
    echo "   source ~/.zshrc"
fi

echo ""
echo -e "${GREEN}✓${NC} Installation complete."
echo ""
echo "Test with:"
echo "  jira check"
echo "  jira --project ADO check"
